-- সমস্যাটা ছিল: comments টেবিলে avatar_url নামের কোনো কলামই ছিল না,
-- তাই কমেন্ট পোস্ট করার সময় প্রোফাইল ছবি সেভ হতো না এবং কমেন্ট লিস্টে
-- সবসময় নামের প্রথম অক্ষর (initial) দেখানো হতো, আসল ছবি কখনোই না।
--
-- এই স্ক্রিপ্ট শুধু comments টেবিলে avatar_url কলাম যোগ করে।
-- এর আগে যেসব কমেন্ট করা হয়েছে সেগুলোর avatar_url খালি (NULL) থাকবে
-- এবং initial-ই দেখাবে — এটা normal, কিছু ভাঙবে না। এর পর থেকে নতুন
-- কমেন্ট করলে (script.js ইতিমধ্যে আপডেট করা আছে) আসল প্রোফাইল ছবি সেভ হবে।

alter table public.comments
    add column if not exists avatar_url text;
